      let f = 0;
      if (t === 3) { if (n > 0.72) f = 6; }
      else if (lat > 50 && lon > 56) f = n > 0.3 ? (lon < 92 && lat < 58 && r < 0.35 ? 5 : 2) : 0;
      else if (lat > 40 && lon > 120 && lon < 142) f = n > 0.4 ? (r < 0.5 ? 2 : 1) : 0;
      else if (lat > 30 && lon > 128) f = n > 0.35 ? (r < 0.4 ? 2 : 1) : 0;
      else if (lat < 24 && lon > 92) f = n > 0.3 ? (lat < 14 ? 3 : r < 0.4 ? 3 : 1) : 0;
      else if (lat < 33.5 && lon > 102 && lon < 122) f = n > 0.48 ? (lat < 31 && lat > 25 && U.noise(x / 6, y / 6, 33) > 0.6 ? 4 : 1) : 0;
      else if (lat < 25 && lon > 72 && lon < 92) f = n > 0.55 ? (lat < 15 || lon > 86 ? 3 : 1) : 0;
      else if (lat > 36 && lat < 39 && lon > 48 && lon < 56) f = n > 0.3 ? 1 : 0;
      else if (lat > 41 && lat < 44 && lon > 38 && lon < 46) f = n > 0.4 ? 1 : 0;
      else if (lat > 48 && lon < 56) f = n > 0.42 ? (r < 0.5 ? 1 : 5) : 0;
      else if (t === 5 && lat > 42 && n > 0.45) f = 2;
